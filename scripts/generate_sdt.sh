#!/usr/bin/env bash
# Generate the system device tree for one carrier.
#
# generate_sdt.sh <xsa> <sdtgen> <dtc> <cpp> <dtsi>...
#
# The SOM and carrier dtsi files are concatenated, in order, into one user
# tree next to the XSA: SDTGen copies -user_dts into the SDT as a single file,
# so an #include between them would not survive into the Yocto build.
# The result is compiled once so syntax and reference errors surface here
# rather than in gen-machine-conf. Edit the sources, never build/ outputs.
set -euo pipefail

xsa=$(realpath "${1:?XSA required}")
sdtgen=${2:-sdtgen}
dtc=${3:-dtc}
cpp=${4:-cpp}
shift 4
(( $# > 0 )) || { echo 'SDT generation: at least one dtsi required' >&2; exit 1; }
out_dir=$(dirname "$xsa")
name=$(basename "$xsa" .xsa)
sdt_dir="$out_dir/sdt"
log_dir="$out_dir/logs"
user_dts="$out_dir/$name.dtsi"

fail() { printf 'SDT generation: %s\n' "$*" >&2; exit 1; }

command -v "$sdtgen" >/dev/null || fail "SDTGen not found; source Vivado settings64.sh or set SDTGEN=/path/to/sdtgen."
command -v "$dtc" >/dev/null || fail "device-tree compiler not found; source Vivado settings64.sh or set DTC=/path/to/dtc."
command -v "$cpp" >/dev/null || fail "C preprocessor not found; install cpp or set DTS_CPP=/path/to/cpp."

# Remove the stamp first so a failed run never looks up to date.
rm -f "$sdt_dir/.generated"
mkdir -p "$sdt_dir" "$log_dir"

{
    printf '/* Generated by scripts/generate_sdt.sh from:'
    printf ' %s' "$@"
    printf '. Do not edit. */\n'
    for dtsi in "$@"; do
        [[ -s "$dtsi" ]] || fail "missing $dtsi"
        printf '\n/* ---- %s ---- */\n' "$dtsi"
        cat "$dtsi"
    done
} > "$user_dts"

(cd "$out_dir" && "$sdtgen" -xsa "$xsa" -dir "$sdt_dir" -user_dts "$user_dts") \
    > "$log_dir/sdtgen.log" 2>&1 || { cat "$log_dir/sdtgen.log" >&2; fail "sdtgen failed; see $log_dir/sdtgen.log"; }
[[ -s "$sdt_dir/system-top.dts" ]] || fail 'sdtgen did not produce system-top.dts.'

"$cpp" -nostdinc -undef -D__DTS__ -x assembler-with-cpp \
    -I "$sdt_dir" -I "$sdt_dir/include" \
    "$sdt_dir/system-top.dts" -o "$sdt_dir/system-top.pp.dts"
"$dtc" -I dts -O dtb -o "$sdt_dir/system-top.dtb" "$sdt_dir/system-top.pp.dts" \
    2> "$log_dir/dtc.log" || { cat "$log_dir/dtc.log" >&2; fail "dtc failed; see $log_dir/dtc.log"; }
touch "$sdt_dir/.generated"
